from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path

from .config import CONFIG_FILE, ProjectConfig, is_valid_name, load_config, write_config
from .errors import ConfigError, PabrikonError, UsageError
from .theme import ThemeDirectory, read_theme_directories, render_index_theme

SOURCE_SUBDIR = "scalable"

# Freedesktop icon names are file stems looked up by name; keep them to
# characters that are safe as path components and in index.theme.
ICON_NAME_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+@-]*$")

ALIASES_TEMPLATE = """\
# Icon aliases, one table per icon directory.
# Each key is the alias name; the value is the target icon in the same
# directory ("target") or in another directory ("places/target").
#
# [places]
# folder-home = "user-home"
#
# [categories]
# applications-mathematics = "apps/accessories-calculator"
"""


def is_valid_icon_name(name: str) -> bool:
    """Return whether an icon stem is safe for theme filenames and path components."""
    return bool(ICON_NAME_PATTERN.match(name))


def walk_files(directory: Path) -> list[Path]:
    """Return files and symbolic links under ``directory``, sorted, without following links."""
    found: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(directory):
        base = Path(dirpath)
        found.extend(base / name for name in filenames)
        found.extend(base / name for name in dirnames if (base / name).is_symlink())
    return sorted(found)


@dataclass(frozen=True)
class IconSource:
    context: str
    name: str
    path: Path
    directory: str
    directory_type: str
    size: int
    scale: int = 1

    @property
    def fixed_size(self) -> int | None:
        """Return the declared size for fixed directories, otherwise ``None``."""
        return self.size if self.directory_type != "Scalable" else None

    @property
    def key(self) -> str:
        """Return the source icon's canonical context/name identifier."""
        return f"{self.context}/{self.name}"


@dataclass(frozen=True)
class Project:
    root: Path
    config: ProjectConfig

    @classmethod
    def load(cls, path: Path) -> "Project":
        """Resolve a project root and load its Pabrikon configuration."""
        root = path.resolve()
        config_path = root / CONFIG_FILE
        old_config_path = root / "pabrikon.toml"
        if not config_path.is_file() and old_config_path.is_file():
            raise ConfigError(
                f"configuration found at {old_config_path}; Pabrikon now expects {config_path}",
                hint=f"Move the file to {CONFIG_FILE} and try again.",
            )
        return cls(root=root, config=load_config(config_path, default_name=root.name))

    @property
    def icons_dir(self) -> Path:
        """Return the root directory containing editable icon sources."""
        return self.root / "icons"

    @property
    def build_dir(self) -> Path:
        """Return the isolated directory used for generated theme assets."""
        return self.root / "build"

    @property
    def dist_dir(self) -> Path:
        """Return the directory used for archives and optimized copies."""
        return self.root / "dist"

    @property
    def data_dir(self) -> Path:
        """Return the directory containing project metadata such as aliases."""
        return self.root / "data"

    @property
    def aliases_file(self) -> Path:
        """Return the configured location of the optional alias definitions."""
        return self.data_dir / "aliases.toml"

    @property
    def index_theme(self) -> Path:
        """Return the path to the theme's root index.theme metadata file."""
        return self.root / "index.theme"

    def check_build_dir(self) -> None:
        """Refuse to work on a build/ that is a link, which could redirect writes or deletes outside the project."""
        if self.build_dir.is_symlink():
            raise PabrikonError(
                f"{self.build_dir} is a symbolic link; refusing to modify files through it",
                hint="Remove the link; build/ is generated by `pabrikon build`.",
            )

    def source_dir(self, context: str) -> Path:
        """Return the scalable SVG source directory for one icon context."""
        return self.icons_dir / context / SOURCE_SUBDIR

    def require_directory(self, context: str) -> None:
        """Raise a usage error when a requested context is not enabled."""
        if context not in self.config.build.directories:
            raise UsageError(
                f"directory {context!r} is not enabled in {CONFIG_FILE}",
                hint=f"Enabled directories: {', '.join(self.config.build.directories)}",
            )

    def sources(self, context: str | None = None) -> list[IconSource]:
        """Return SVG sources from every declared icon directory, sorted.

        Symbolic links are skipped: a linked source may point outside the
        project, and `pabrikon validate` reports them instead.
        """
        found: list[IconSource] = []
        for spec in self.theme_directories():
            if spec.context not in self.config.build.directories or (context and spec.context != context):
                continue
            source_dir = self.icons_dir / spec.path
            if not source_dir.is_dir() or source_dir.is_symlink():
                continue
            for path in sorted(source_dir.glob("*.svg")):
                if path.is_file() and not path.is_symlink():
                    found.append(
                        IconSource(
                            context=spec.context,
                            name=path.stem,
                            path=path,
                            directory=spec.path,
                            directory_type=spec.directory_type,
                            size=spec.size,
                            scale=spec.scale,
                        )
                    )
        return found

    def theme_directories(self) -> list[ThemeDirectory]:
        """Return directory metadata declared by the project's index.theme."""
        try:
            return read_theme_directories(self.index_theme, self.config)
        except (OSError, UnicodeError, ValueError):
            return []


def init_project(target: Path, name: str | None = None) -> tuple[Path, list[Path]]:
    """Create a project in ``target`` without overwriting existing files.

    Returns the project root and the paths that were created.
    """
    root = target.resolve()
    project_name = name or root.name
    if not is_valid_name(project_name):
        raise UsageError(
            f"invalid project name {project_name!r}",
            hint="Use letters, digits, '.', '_' or '-', starting with a letter or digit.",
        )
    if root.exists() and not root.is_dir():
        raise PabrikonError(f"{root} exists and is not a directory")
    if (root / "data").is_symlink():
        raise PabrikonError(f"{root / 'data'} is a symbolic link; refusing to write project files through it")
    if (root / CONFIG_FILE).exists() or (root / CONFIG_FILE).is_symlink():
        raise PabrikonError(
            f"{root} is already a Pabrikon project ({CONFIG_FILE} exists)",
            hint="Edit the existing configuration instead of re-initializing.",
        )
    if (root / "pabrikon.toml").is_file():
        raise PabrikonError(
            f"root-level pabrikon.toml found in {root}",
            hint=f"Move it to {CONFIG_FILE} before initializing this project.",
        )

    config = ProjectConfig.default(project_name)
    project = Project(root=root, config=config)
    created: list[Path] = []

    for directory in [root, project.data_dir, project.dist_dir, project.icons_dir] + [
        project.source_dir(ctx) for ctx in config.build.directories
    ]:
        if not directory.exists():
            directory.mkdir(parents=True)
            created.append(directory)

    readme = (
        f"# {config.theme.name}\n\n"
        "Linux icon theme managed with Pabrikon.\n\n"
        "Put SVG sources in `icons/<directory>/scalable/`, then:\n\n"
        "```bash\n"
        "pabrikon validate\n"
        "pabrikon build\n"
        "pabrikon package\n"
        "```\n"
    )
    files = {
        root / CONFIG_FILE: None,
        root / "README.md": readme,
        project.index_theme: render_index_theme(config),
        project.aliases_file: ALIASES_TEMPLATE,
    }
    for path, content in files.items():
        if path.exists():
            continue
        if content is None:
            write_config(path, config)
        else:
            path.write_text(content, encoding="utf-8")
        created.append(path)
    return root, created
